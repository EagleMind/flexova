#!/usr/bin/env node
// Generates src/allowlist.ts from spec/profile/profile-1.0.json: the compact subset of the profile a viewer
// needs to rebuild content safely (spec section 9). Usage: node scripts/gen-allowlist.mjs [--check]
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..", "..");
const out = join(here, "..", "src", "allowlist.ts");

export function generate() {
  const p = JSON.parse(readFileSync(join(root, "spec", "profile", "profile-1.0.json"), "utf8"));
  // Attribute type codes: "id" | "text" | "boolean" | "link" | "uri:<kind,...>" | "re:<type>" | "enum:<a|b>"
  const code = (spec, targets) => {
    if (typeof spec !== "string") return "enum:" + spec.enum.join("|");
    const t = p.attributeTypes[spec];
    if (t.kind === "local-uri") return "uri:" + (targets ?? []).join(",");
    if (t.kind === "link-uri") return "link";
    if (t.kind === "boolean") return "boolean";
    if (spec === "id" || spec === "text") return spec;
    return "re:" + spec;
  };
  const skip = Object.entries(p.elements)
    .filter(
      ([name, d]) =>
        d.category === "root" ||
        (d.category === "structural" && ["head", "title", "meta", "link", "body"].includes(name)),
    )
    .map(([name]) => name);
  const elements = {};
  for (const [name, d] of Object.entries(p.elements)) {
    if (skip.includes(name)) continue;
    const attrs = {};
    for (const [a, spec] of Object.entries(d.attributes ?? {}))
      attrs[a] = code(spec, d.targets?.[a]);
    elements[name] = attrs;
  }
  const globals = {};
  for (const [a, spec] of Object.entries(p.globalAttributes)) globals[a] = code(spec);
  const patterns = {};
  for (const [name, t] of Object.entries(p.attributeTypes))
    if (t.pattern && name !== "id") patterns[name] = t.pattern;
  const data = {
    elements,
    globals,
    patterns,
    idPattern: p.attributeTypes.id.pattern,
    linkSchemes: p.attributeTypes["link-uri"].schemes,
    forbidden: [...p.forbiddenElements, ...skip],
    forbiddenAttributes: p.forbiddenAttributePatterns,
    mathElements: p.mathml.elements,
    mathAttributes: p.mathml.attributes,
    mediaTypes: p.mediaTypes,
    entryName: p.entryNamePattern,
    limits: p.limits,
  };
  return (
    "// GENERATED by scripts/gen-allowlist.mjs from spec/profile/profile-1.0.json. Do not edit.\n" +
    "// Regenerate with `pnpm --filter @flexova/viewer gen` after changing the profile.\n" +
    `export const PROFILE = ${JSON.stringify(data)} as const;\n`
  );
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = generate();
  if (process.argv.includes("--check")) {
    if (readFileSync(out, "utf8") !== text) {
      console.error("src/allowlist.ts is out of date; run: pnpm --filter @flexova/viewer gen");
      process.exit(1);
    }
  } else {
    writeFileSync(out, text);
    console.log(`wrote ${out}`);
  }
}
