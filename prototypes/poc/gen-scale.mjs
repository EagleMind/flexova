// Generate a ~1000-page report with ~20 MB of photos, emitted two ways:
//   plain.fdoc.html  — static-first: canonical XHTML inline, images as data: URIs, zero JS
//   sealed.fdoc.html — every chapter/image is a JWE-keyed AES-GCM entry; runtime decrypts + sanitizes lazily
import * as F from "./fdoc-jwe.mjs";
import { createRequire } from "node:module";
const { chromium } = createRequire(import.meta.url)("playwright");
import { readFileSync, writeFileSync } from "node:fs";
import { gzipSync } from "node:zlib";
import { createHash } from "node:crypto";

const CHAPTERS = 100, PAGES_PER_CH = 10, WORDS_PER_PAGE = 450, TARGET_IMG_BYTES = 20e6;
let seed = 42; const rnd = () => ((seed = (seed * 1664525 + 1013904223) >>> 0) / 2 ** 32);
const VOCAB = "the of and to in system report quarter revenue growth customer risk control audit model data process service network value market operation cost analysis review policy security team product strategy result impact".split(" ");
const words = (n) => Array.from({ length: n }, () => VOCAB[(rnd() * VOCAB.length) | 0]).join(" ");
const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;");

// --- photos generated by Chromium's own JPEG encoder (noise + gradients ≈ photographic entropy) ---
const browser = await chromium.launch();
const page = await browser.newPage();
const images = [];
for (let total = 0; total < TARGET_IMG_BYTES;) {
  const b64 = await page.evaluate((s) => {
    const c = Object.assign(document.createElement("canvas"), { width: 1600, height: 1000 }), x = c.getContext("2d");
    const g = x.createLinearGradient(0, 0, 1600, 1000); g.addColorStop(0, `hsl(${s * 37 % 360},60%,50%)`); g.addColorStop(1, `hsl(${s * 91 % 360},60%,30%)`);
    x.fillStyle = g; x.fillRect(0, 0, 1600, 1000);
    const d = x.getImageData(0, 0, 1600, 1000); for (let i = 0; i < d.data.length; i += 4) { const n = (Math.random() - .5) * 60; d.data[i] += n; d.data[i + 1] += n; d.data[i + 2] += n; }
    x.putImageData(d, 0, 0); return c.toDataURL("image/jpeg", 0.8).split(",")[1];
  }, images.length);
  const bytes = Buffer.from(b64, "base64"); images.push(bytes); total += bytes.length;
}
await browser.close();
const imgBytes = images.reduce((n, b) => n + b.length, 0);

// --- canonical content: one strict-XHTML file per chapter (the format's real content model) ---
const imgEvery = Math.max(1, Math.floor(CHAPTERS / images.length));
const chapters = [];
for (let c = 1; c <= CHAPTERS; c++) {
  let x = `<section xmlns="http://www.w3.org/1999/xhtml" id="ch${c}" class="fd-chapter"><h2 id="h-${c}">Chapter ${c}: ${esc(words(4))}</h2>`;
  for (let p = 0; p < PAGES_PER_CH; p++) for (let k = 0; k < 3; k++) x += `<p id="p-${c}-${p}-${k}">${esc(words(WORDS_PER_PAGE / 3))}</p>`;
  x += `<div class="fd-table" role="region" aria-label="Table ${c}" tabindex="0"><table><thead><tr>${Array.from({ length: 9 }, (_, i) => `<th scope="col">Metric ${i}</th>`).join("")}</tr></thead><tbody>`;
  for (let r = 0; r < 12; r++) x += `<tr>${Array.from({ length: 9 }, () => `<td>${(rnd() * 1e6).toFixed(2)}</td>`).join("")}</tr>`;
  x += `</tbody></table></div><pre><code>${esc("SELECT region, SUM(revenue) AS total_revenue_in_reporting_currency FROM fact_sales WHERE quarter = 'Q3' GROUP BY region;")}</code></pre>`;
  const imgIdx = (c - 1) / imgEvery;
  if (Number.isInteger(imgIdx) && imgIdx < images.length)
    x += `<figure id="fig-${imgIdx}"><img src="asset:img-${imgIdx}" alt="Figure ${imgIdx}: chart of ${esc(words(5))}" width="1600" height="1000"/><figcaption>Figure ${imgIdx}</figcaption></figure>`;
  chapters.push(x + "</section>");
}
const textBytes = chapters.reduce((n, s) => n + s.length, 0);

const CSS = readFileSync(new URL("./base.css", import.meta.url), "utf8");
const sha = (s) => "sha256-" + createHash("sha256").update(s).digest("base64");
const shell = (title, csp, body) => `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="color-scheme" content="light dark"><meta http-equiv="Content-Security-Policy" content="${csp}">
<title>${title}</title><style>${CSS}</style></head><body>${body}</body></html>`;

// --- 1. plaintext, static-first ---
const plainBody = `<main><h1>Annual Operations Report</h1>` + chapters.map((x) =>
  x.replace(' xmlns="http://www.w3.org/1999/xhtml"', "").replace(/src="asset:img-(\d+)"/, (_, i) =>
    `src="data:image/jpeg;base64,${images[i].toString("base64")}" loading="lazy" decoding="async"`)).join("") + `</main>`;
const plainCsp = `default-src 'none'; style-src '${sha(CSS)}'; img-src data:; base-uri 'none'; form-action 'none'`;
writeFileSync(new URL("./plain.fdoc.html", import.meta.url), shell("Annual Operations Report", plainCsp, plainBody));

// --- 2. sealed ---
const dek = F.newDek();
const entries = [];
for (let c = 0; c < chapters.length; c++) entries.push([`content/ch${c + 1}.xhtml.gz`, await F.sealEntry(dek, `content/ch${c + 1}.xhtml.gz`, gzipSync(chapters[c]))]);
for (let i = 0; i < images.length; i++) entries.push([`assets/img-${i}.jpg`, await F.sealEntry(dek, `assets/img-${i}.jpg`, images[i])]);
const keyring = { v: 1, docId: "urn:uuid:scale-test", dek: F.b64u(dek), meta: { title: "Annual Operations Report" },
  spine: chapters.map((_, c) => `content/ch${c + 1}.xhtml.gz`), assets: Object.fromEntries(images.map((_, i) => [`img-${i}`, { path: `assets/img-${i}.jpg`, type: "image/jpeg" }])) };
const jwe = await F.sealKeyring(keyring, [{ type: "passphrase", passphrase: "correct horse battery staple", kid: "passphrase" }]);
const lib = readFileSync(new URL("./fdoc-jwe.mjs", import.meta.url), "utf8").replace(/^export /gm, "");
const runtime = lib + readFileSync(new URL("./runtime.js", import.meta.url), "utf8");
const sealedCsp = `default-src 'none'; script-src '${sha(runtime)}'; style-src '${sha(CSS)}'; img-src blob:; base-uri 'none'; form-action 'none'`;
const sealedBody = `<main><form id="unlock"><label>Passphrase <input id="pass" type="password" autocomplete="off"/></label> <button>Open</button> <output id="err"></output></form>
<noscript>This document is encrypted. Open it in a browser with JavaScript enabled, or at https://reader.example.org.</noscript><div id="doc"></div></main>
<script type="application/jose+json" id="fd-keyring">${JSON.stringify(jwe).replace(/</g, "\\u003c")}</script>
${entries.map(([p, b]) => `<script type="application/vnd.flowdoc.entry" data-path="${p}">${Buffer.from(b).toString("base64")}</script>`).join("\n")}
<script>${runtime}</script>`;
writeFileSync(new URL("./sealed.fdoc.html", import.meta.url), shell("Encrypted document", sealedCsp, sealedBody));

const mb = (n) => (n / 1e6).toFixed(1) + " MB";
console.log(`content: ${CHAPTERS * PAGES_PER_CH} pages, ${mb(textBytes)} XHTML; ${images.length} photos, ${mb(imgBytes)}`);
console.log(`plain.fdoc.html  ${mb(plainBody.length)}   sealed.fdoc.html ${mb(sealedBody.length)}   runtime ${(runtime.length / 1024).toFixed(1)} KB unminified`);
