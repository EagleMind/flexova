"""Design tokens: validation, WCAG contrast checks and compilation to CSS.
compile_tokens() output is specified byte-for-byte by conformance/vectors/compile-tokens.json."""

import re

COLOR_NAME = re.compile(r"[a-z][a-z0-9-]{0,31}")
HEX = re.compile(r"#([0-9a-fA-F]{3}|[0-9a-fA-F]{6})")
FONT_KEYS = ("body", "heading", "mono")
FONT_STACKS = {
    "system": 'system-ui,-apple-system,"Segoe UI",Roboto,"Noto Sans",sans-serif',
    "serif": 'Charter,"Iowan Old Style",Georgia,"Times New Roman",serif',
    "sans": '"Helvetica Neue",Arial,"Noto Sans",sans-serif',
    "mono": "ui-monospace,SFMono-Regular,Menlo,Consolas,monospace",
}
DEFAULT_COLORS = [
    ("fg", "#1a1a1a", "#e8e6e3"),
    ("bg", "#ffffff", "#121212"),
    ("accent", "#0b5fff", "#7aa7ff"),
    ("muted", "#52525b", "#a1a1aa"),
    ("surface", "#f4f4f5", "#1e1e22"),
    ("note-bg", "#eef4ff", "#16233d"),
    ("warning-bg", "#fff4e5", "#3a2a12"),
]
TEXT_COLORS = ("fg", "accent", "muted")  # must reach MIN_CONTRAST against bg
MIN_CONTRAST = 4.5


def is_integer(value) -> bool:
    """JSON integer as both Python and JavaScript see it (5 and 5.0 are the same number in JSON)."""
    if isinstance(value, bool):
        return False
    return isinstance(value, int) or (isinstance(value, float) and value.is_integer())


def valid_color(name, value) -> bool:
    return (
        isinstance(name, str)
        and COLOR_NAME.fullmatch(name) is not None
        and isinstance(value, dict)
        and set(value) == {"light", "dark"}
        and all(isinstance(value[m], str) and HEX.fullmatch(value[m]) for m in ("light", "dark"))
    )


def valid_font(value) -> bool:
    return isinstance(value, dict) and all(
        k in FONT_KEYS and isinstance(value[k], str) and value[k] in FONT_STACKS for k in value
    )


def valid_measure(value) -> bool:
    return is_integer(value) and 40 <= value <= 100


def _luminance(hex_color: str) -> float:
    h = hex_color[1:]
    if len(h) == 3:
        h = "".join(ch * 2 for ch in h)
    channels = []
    for i in (0, 2, 4):
        v = int(h[i : i + 2], 16) / 255
        channels.append(v / 12.92 if v <= 0.04045 else ((v + 0.055) / 1.055) ** 2.4)
    return 0.2126 * channels[0] + 0.7152 * channels[1] + 0.0722 * channels[2]


def contrast(a: str, b: str) -> float:
    la, lb = _luminance(a), _luminance(b)
    hi, lo = max(la, lb), min(la, lb)
    return (hi + 0.05) / (lo + 0.05)


def check_tokens(tokens, c, path: str) -> None:
    if not isinstance(tokens, dict):
        c.add("MAN_INVALID", path, "tokens must be an object")
        return
    colors = {}
    if "color" in tokens:
        group = tokens["color"]
        if not isinstance(group, dict):
            c.add("MAN_INVALID_TOKEN", path, "color must be an object")
        else:
            for name in sorted(group):
                if valid_color(name, group[name]):
                    colors[name] = group[name]
                else:
                    c.add("MAN_INVALID_TOKEN", path, f"color.{name}")
    if "font" in tokens and not valid_font(tokens["font"]):
        c.add("MAN_INVALID_TOKEN", path, "font")
    if "measure" in tokens and not valid_measure(tokens["measure"]):
        c.add("MAN_INVALID_TOKEN", path, "measure")
    bg = colors.get("bg")
    if bg:
        for name in TEXT_COLORS:
            if name in colors and any(contrast(colors[name][m], bg[m]) < MIN_CONTRAST for m in ("light", "dark")):
                c.add("MAN_LOW_CONTRAST", path, f"color.{name} on color.bg")


def compile_tokens(tokens=None) -> str:
    """Compile design tokens into the package stylesheet. Invalid tokens are ignored (validation reports them)."""
    tokens = tokens if isinstance(tokens, dict) else {}
    group = tokens.get("color") if isinstance(tokens.get("color"), dict) else {}
    colors = {name: [light, dark] for name, light, dark in DEFAULT_COLORS}
    for name in sorted(group):
        if valid_color(name, group[name]):
            colors[name] = [group[name]["light"].lower(), group[name]["dark"].lower()]
    defaults = [name for name, _, _ in DEFAULT_COLORS]
    order = defaults + sorted(n for n in colors if n not in defaults)
    font = tokens.get("font") if valid_font(tokens.get("font")) else {}
    body = font.get("body", "system")
    fonts = {"body": body, "heading": font.get("heading", body), "mono": font.get("mono", "mono")}
    measure = int(tokens["measure"]) if valid_measure(tokens.get("measure")) else 68

    light = "".join(f"--flexova-{n}:{colors[n][0]};" for n in order)
    dark = "".join(f"--flexova-{n}:{colors[n][1]};" for n in order)
    font_vars = "".join(f"--flexova-font-{k}:{FONT_STACKS[fonts[k]]};" for k in FONT_KEYS)
    lines = [
        "/* Generated by Flexova from design tokens. Do not edit. */",
        f":root{{color-scheme:light dark;{light}{font_vars}--flexova-measure:{measure}ch}}",
        f"@media (prefers-color-scheme:dark){{:root{{{dark.rstrip(';')}}}}}",
        "html{-webkit-text-size-adjust:100%;text-size-adjust:100%}",
        "body{margin:0 auto;max-width:var(--flexova-measure);padding:0 1rem;background:var(--flexova-bg);"
        "color:var(--flexova-fg);font-family:var(--flexova-font-body);font-size:1.0625rem;line-height:1.6;"
        "overflow-wrap:break-word}",
        "h1,h2,h3,h4,h5,h6{font-family:var(--flexova-font-heading);line-height:1.25}",
        "a{color:var(--flexova-accent)}",
        "img{max-width:100%;height:auto}",
        "figure{margin-inline:0}",
        "figcaption{color:var(--flexova-muted);font-size:.9em}",
        "pre{overflow-x:auto;padding:1rem;background:var(--flexova-surface)}",
        "code,kbd,samp,pre{font-family:var(--flexova-font-mono)}",
        "table{border-collapse:collapse;max-width:100%}",
        "th,td{padding:.4em .6em;text-align:start;border-bottom:1px solid var(--flexova-surface)}",
        "aside[role=note]{padding:.5em 1em;border-radius:6px;background:var(--flexova-note-bg)}",
        "aside[data-flexova-variant=warning],aside[data-flexova-variant=caution]{background:var(--flexova-warning-bg)}",
        "@media (prefers-color-scheme:dark){img{filter:brightness(.9)}}",
    ]
    return "\n".join(lines) + "\n"
